"""Regenerate LEADERBOARD.md from the questions/ tree.

Reads the frontmatter of every file under questions/<q>/routes/ and attempts/ and produces:
  - questions ranked by breadth (accepted routes), with strategies used and attempt counts
  - contributors ranked by depth-weighted score (sum of route depths)
  - a question-by-year grid of accepted routes
  - strategy coverage across questions
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from strategy_map import norm as canon_strategy  # noqa: E402
QUESTIONS = ROOT / "questions"


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    meta = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip()
    return meta


routes, attempts, questions = [], [], {}
for qdir in sorted(p for p in QUESTIONS.iterdir() if p.is_dir()):
    qmeta = frontmatter(qdir / "question.md") if (qdir / "question.md").exists() else {}
    questions[qdir.name] = qmeta
    for f in sorted((qdir / "routes").glob("*.md")) if (qdir / "routes").exists() else []:
        routes.append({"question": qdir.name, **frontmatter(f)})
    for f in sorted((qdir / "attempts").glob("*.md")) if (qdir / "attempts").exists() else []:
        attempts.append({"question": qdir.name, **frontmatter(f)})

by_q = defaultdict(list)
for r in routes:
    by_q[r["question"]].append(r)
att_by_q = defaultdict(list)
for a in attempts:
    att_by_q[a["question"]].append(a)

lines = ["# Leaderboard", "", "_Generated by `scripts/build_leaderboard.py`; do not edit by hand._", ""]

def typed_keys(route, resolution):
    """Identity keys of a route's typed landmarks. R0 = (kind, subject, object, relation); R2 adds yardstick."""
    keys = set()
    for k in sorted(k for k in route if k.startswith("typed_")):
        parts = [p.strip().lower() for p in route[k].split("|")]
        if len(parts) < 5:
            continue
        key = tuple(parts[:4]) + ((parts[4],) if resolution == "R2" else ())
        keys.add(key)
    return keys

def breadth_at(rs, resolution):
    """Count routes that introduce at least one new typed key, in depth order. Untyped routes count as new."""
    seen, n = set(), 0
    for r in sorted(rs, key=lambda r: int(r.get("depth", 0))):
        keys = typed_keys(r, resolution)
        if not keys or keys - seen:
            n += 1
        seen |= keys
    return n

lines += ["## Questions by breadth", "", "_breadth = routes the referee accepted (criterion as stamped); R0 / R2 = routes that introduce a new typed landmark at coarse / fine resolution (LANDMARKS.md); untyped routes count at both._", "",
          "| rank | question | breadth | R0 | R2 | strategies | attempts (wrong / duplicate / ill-formed) | criterion |", "|---|---|---|---|---|---|---|---|"]
ranked = sorted(questions, key=lambda q: -len(by_q[q]))
for i, q in enumerate(ranked, 1):
    rs = by_q[q]
    strategies = ", ".join(sorted({canon_strategy(r.get("strategy")) for r in rs})) or "—"
    verdicts = [a.get("verdict", "") for a in att_by_q[q]]
    att = f"{len(verdicts)} ({verdicts.count('WRONG')} / {verdicts.count('DUPLICATE')} / {verdicts.count('ILL-FORMED')})"
    crit = ", ".join(sorted({r.get("criterion", "?") for r in rs})) or "—"
    title = questions[q].get("title", q)
    r0 = breadth_at(rs, "R0") if rs else 0
    r2 = breadth_at(rs, "R2") if rs else 0
    lines.append(f"| {i} | {title} (`{q}`) | {len(rs)} | {r0} | {r2} | {strategies} | {att} | {crit} |")

lines += ["", "## Contributors by depth-weighted score", "", "_Score = sum over accepted routes of the route's depth (routes already accepted when it was found, plus one)._", "", "| rank | contributor | score | routes | deepest |", "|---|---|---|---|---|"]
score, count, deepest = defaultdict(int), defaultdict(int), defaultdict(int)
for r in routes:
    c = r.get("contributor", "unknown")
    d = int(r.get("depth", 1))
    score[c] += d
    count[c] += 1
    deepest[c] = max(deepest[c], d)
for i, c in enumerate(sorted(score, key=lambda c: -score[c]), 1):
    lines.append(f"| {i} | {c} | {score[c]} | {count[c]} | {deepest[c]} |")

def model_of(contributor):
    name = contributor.split("(")[0].strip().lower()
    for alias, canon in (("claude-sonnet-4.5", "sonnet"), ("claude-opus", "opus"), ("claude-sonnet", "sonnet")):
        if name.startswith(alias):
            return canon
    return name or "unknown"

lines += ["", "## Models by routes discovered", "", "_Seats (duelist A/B, blind player n, extender) collapsed to the model that played them._", "", "| rank | model | routes | depth-weighted score | questions touched | deepest |", "|---|---|---|---|---|---|"]
m_score, m_count, m_q, m_deep = defaultdict(int), defaultdict(int), defaultdict(set), defaultdict(int)
for r in routes:
    m = model_of(r.get("contributor", ""))
    d = int(r.get("depth", 1))
    m_score[m] += d
    m_count[m] += 1
    m_q[m].add(r["question"])
    m_deep[m] = max(m_deep[m], d)
for i, m in enumerate(sorted(m_score, key=lambda m: (-m_count[m], -m_score[m])), 1):
    lines.append(f"| {i} | {m} | {m_count[m]} | {m_score[m]} | {len(m_q[m])} | {m_deep[m]} |")

years = sorted({r.get("date", "")[:4] for r in routes if r.get("date")})
lines += ["", "## Accepted routes by question and year", "", "| question | " + " | ".join(years) + " | total |", "|---|" + "---|" * (len(years) + 1)]
for q in ranked:
    cells = [str(sum(1 for r in by_q[q] if r.get("date", "").startswith(y))) for y in years]
    lines.append(f"| `{q}` | " + " | ".join(cells) + f" | {len(by_q[q])} |")

lines += ["", "## Strategy coverage", "", "| strategy | questions with an accepted route | routes |", "|---|---|---|"]
strat_q, strat_n = defaultdict(set), defaultdict(int)
for r in routes:
    strat_q[canon_strategy(r.get("strategy"))].add(r["question"])
    strat_n[canon_strategy(r.get("strategy"))] += 1
for s in sorted(strat_q, key=lambda s: (-len(strat_q[s]), s)):
    lines.append(f"| `{s}` | {', '.join(sorted(strat_q[s]))} | {strat_n[s]} |")

lines += ["", "## Where intuition overreached", "", "| question | attempt | verdict | strategy | reason |", "|---|---|---|---|---|"]
for a in attempts:
    lines.append(f"| `{a['question']}` | {a.get('title', a.get('id', '?'))} | {a.get('verdict', '?')} | {a.get('strategy', '?')} | {a.get('reason', '')} |")

(ROOT / "LEADERBOARD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"LEADERBOARD.md written: {len(questions)} questions, {len(routes)} routes, {len(attempts)} attempts")
