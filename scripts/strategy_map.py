"""Question-by-strategy map (EXPANDING_THE_PROBLEM_SPACE.md §8): for every strategy named on any judged
chain, which questions it WORKED on (an accepted route), where it was ATTEMPTED AND FAILED (a rejected
chain, with the verdict), and which questions are UNTRIED. Proposed/ruled-out states are curator
annotations and are read from STRATEGIES.md only when a line there starts with `proposed:` or `ruled-out:`
(format: `proposed: <strategy> on <question-id>` / `ruled-out: <strategy> on <question-id> — reason`).

  python scripts/strategy_map.py        → STRATEGY_MAP.md
"""
import re
from collections import defaultdict
from pathlib import Path

from play import frontmatter, read, ROOT

_ALIASES = None

def load_aliases():
    global _ALIASES
    if _ALIASES is None:
        _ALIASES = {}
        cat = read(ROOT / "STRATEGIES.md") if (ROOT / "STRATEGIES.md").exists() else ""
        for m in re.finditer(r"^alias:\s*([\w\-]+)\s*=>\s*([\w\-]+)", cat, re.M):
            _ALIASES[m.group(1).lower()] = m.group(2).lower()
    return _ALIASES

def norm(s):
    """Canonical catalogue id for a strategy string as the referee wrote it."""
    s = (s or "").strip()
    s = re.sub(r"^new:\s*", "", s, flags=re.I)
    s = re.sub(r"\s*\(.*\)$", "", s)
    s = s.strip().lower().replace(" ", "-") or "unclassified"
    return load_aliases().get(s, s)

def main():
    worked, failed = defaultdict(set), defaultdict(lambda: defaultdict(list))
    questions = []
    for qdir in sorted(p for p in (ROOT / "questions").iterdir() if p.is_dir()):
        questions.append(qdir.name)
        for f in (qdir / "routes").glob("*.md") if (qdir / "routes").exists() else []:
            worked[norm(frontmatter(read(f)).get("strategy"))].add(qdir.name)
        for f in (qdir / "attempts").glob("*.md") if (qdir / "attempts").exists() else []:
            m = frontmatter(read(f))
            failed[norm(m.get("strategy"))][qdir.name].append(m.get("verdict", "?"))
    annotations = defaultdict(dict)
    cat = read(ROOT / "STRATEGIES.md") if (ROOT / "STRATEGIES.md").exists() else ""
    for kind in ("proposed", "ruled-out"):
        for m in re.finditer(rf"^{kind}:\s*([\w\-]+)\s+on\s+([\w\-]+)", cat, re.M | re.I):
            annotations[norm(m.group(1))][m.group(2)] = kind
    strategies = sorted(set(worked) | set(failed) | set(annotations), key=lambda s: (-len(worked[s]), s))

    lines = ["# Strategy × question map", "", "_Generated by `scripts/strategy_map.py`. W = worked (accepted route); F = attempted and failed (verdicts); P = proposed by a curator; R = ruled out; · = untried._", ""]
    short = {q: q for q in questions}
    lines.append("| strategy | " + " | ".join(f"`{q}`" for q in questions) + " | worked on | failed on |")
    lines.append("|---|" + "---|" * (len(questions) + 2))
    for s in strategies:
        cells = []
        for q in questions:
            if q in worked[s]:
                cells.append("**W**")
            elif q in failed[s]:
                v = failed[s][q]
                cells.append("F:" + "/".join(sorted({x[0] for x in v})))   # W/D/I initials
            elif annotations.get(s, {}).get(q):
                cells.append("P" if annotations[s][q] == "proposed" else "R")
            else:
                cells.append("·")
        lines.append(f"| `{s}` | " + " | ".join(cells) + f" | {len(worked[s])} | {sum(len(v) for v in failed[s].values())} |")
    lines += ["", "## Reading the map", "",
              "- A strategy with many **W** across unrelated families is general; try it on an untried family next.",
              "- An **F** beside a **W** on another question is the interesting cell: the principle is sound somewhere and failed here — a boundary, or a bad execution.",
              "- Rows with **W** on one question only are candidates for transfer instances.",
              "- Columns with few marks are questions the catalogue has barely touched."]
    (ROOT / "STRATEGY_MAP.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"STRATEGY_MAP.md: {len(strategies)} strategies × {len(questions)} questions")

if __name__ == "__main__":
    main()
